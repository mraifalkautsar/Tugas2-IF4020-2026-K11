#!/usr/bin/env python3
"""Render recorded experiments into report tables and standalone histograms.

Requires matplotlib only for rendering; the Go cipher and tests do not.
Run from the repository root after regenerating the documented JSON reports.
"""

import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / "reports/brainrot-v2"
TABLES = ROOT / "docs/laporan/data/v2"
PICTURES = ROOT / "docs/laporan/gambar"


def load(name):
    return json.loads((REPORTS / name).read_text())


def write_rows(name, rows):
    command = {"block-avalanche.tex": "VTwoBlockRows",
               "mode-avalanche.tex": "VTwoModeRows",
               "entropy.tex": "VTwoEntropyRows",
               "roundtrip.tex": "VTwoRoundTripRows",
               "binary-entropy.tex": "VTwoBinaryEntropyRows"}[name]
    (TABLES / name).write_text(
        "% Generated by scripts/render_brainrot_results.py from recorded v2 JSON.\n"
        + "\\newcommand{\\" + command + "}{%\n"
        + "\n".join(" & ".join(map(str, row)) + r"\\" for row in rows) + "\n}\n"
    )


def histogram(report, title, destination):
    fig, axes = plt.subplots(3, 2, figsize=(10, 7), constrained_layout=True)
    datasets = [("Plaintext", report["modes"][0]["plaintext"])] + [
        (entry["mode"], entry["ciphertext"]) for entry in report["modes"]
    ]
    for ax, (label, distribution) in zip(axes.flat, datasets):
        count = distribution["bytes"]
        ax.bar(range(256), [100 * n / count for n in distribution["histogram"]],
               width=1, color="#245b8a")
        ax.axhline(100 / 256, color="#b54a35", linestyle="--", linewidth=0.8)
        ax.set_title(f"{label}: {count} bytes; H={distribution['entropy_bits_per_byte']:.3f}", fontsize=10)
        ax.set_xlim(-0.5, 255.5)
        ax.set_xticks([0, 64, 128, 192, 255])
        ax.set_xlabel("Byte value", fontsize=9)
        ax.set_ylabel("Frequency (%)", fontsize=9)
        ax.tick_params(labelsize=8)
        ax.grid(axis="y", alpha=0.2)
    fig.suptitle(title + "\nY scales vary by panel; dashed line = uniform byte distribution", fontsize=11)
    fig.savefig(destination, dpi=200)
    plt.close(fig)


def main():
    TABLES.mkdir(parents=True, exist_ok=True)
    text = load("text-seed42.json")
    binary = load("binary-seed42.json")
    write_rows("block-avalanche.tex", [
        [label, value["trials"], f"{value['mean_percent']:.3f}",
         value["min_changed_bits"], value["max_changed_bits"]]
        for label, value in [("1 bit plainteks", text["block_plaintext_avalanche"]),
                             ("1 bit kunci", text["block_key_avalanche"])]
    ])
    write_rows("mode-avalanche.tex", [
        [entry["mode"], entry["ciphertext"]["bytes"],
         f"{entry['plaintext_avalanche']['mean_percent']:.3f}",
         f"{entry['key_avalanche']['mean_percent']:.3f}"] for entry in text["modes"]
    ])
    write_rows("entropy.tex", [
        [entry["mode"], entry["ciphertext"]["bytes"],
         f"{entry['plaintext']['entropy_bits_per_byte']:.3f}",
         f"{entry['ciphertext']['entropy_bits_per_byte']:.3f}"] for entry in text["modes"]
    ])
    write_rows("roundtrip.tex", [
        [entry["mode"], entry["plaintext"]["bytes"], binary["modes"][i]["plaintext"]["bytes"],
         f"{entry['ciphertext']['bytes']} / {binary['modes'][i]['ciphertext']['bytes']}",
         f"{'Ya' if entry['round_trip'] else 'Tidak'} / {'Ya' if binary['modes'][i]['round_trip'] else 'Tidak'}"]
        for i, entry in enumerate(text["modes"])
    ])
    write_rows("binary-entropy.tex", [
        [entry["mode"], entry["ciphertext"]["bytes"],
         f"{entry['plaintext']['entropy_bits_per_byte']:.3f}",
         f"{entry['ciphertext']['entropy_bits_per_byte']:.3f}"] for entry in binary["modes"]
    ])
    histogram(text, "Brainrot Cipher v2: repeated text, seed 42",
              PICTURES / "histogram-semua-mode.png")
    histogram(binary, "Brainrot Cipher v2: byte-pattern binary fixture, seed 42",
              PICTURES / "histogram-biner.png")
    print("Rendered five LaTeX tables and both histogram figures")


if __name__ == "__main__":
    main()
